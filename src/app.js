    function initCalcWindow(el, winData) {
        const calc = {
            display: "0",
            acc: null,
            op: null,
            fresh: true,
            error: false,
            mem: 0,
        };
        el._calc = calc;
        const displayEl = el.querySelector("#calc-display");
        const render = () => {
            displayEl.textContent = calc.display;
        };

        el.querySelector(".calc-keys").addEventListener("click", (e) => {
            const btn = /** @type {HTMLElement | null} */ (
                eventTargetElement(e).closest("button[data-key]")
            );
            if (!btn) return;
            calcInput(calc, btn.dataset.key);
            render();
        });

        // Keyboard support — only while this window is the active one
        const onKey = (e) => {
            if (state.windowManager.activeWindowId !== winData.id) return;
            const map = { Escape: "C", Backspace: "Back", Enter: "=" };
            const k = map[e.key] || e.key;
            if (
                /^[0-9.]$/.test(k) ||
                ["+", "-", "*", "/", "%", "="].includes(k)
            ) {
                e.preventDefault();
                calcInput(calc, k);
                render();
            }
        };
        el._calcKeyHandler = onKey;
        document.addEventListener("keydown", onKey);
    }

    function calcInput(calc, key) {
        if (calc.error && key !== "C" && key !== "CE") {
            calcInput(calc, "C");
        }
        const num = () => {
            const v = parseFloat(calc.display);
            return Number.isFinite(v) ? v : 0;
        };
        const fmt = (v) => {
            if (!Number.isFinite(v)) return "Ошибка";
            return String(parseFloat(v.toPrecision(12)));
        };

        if (/^[0-9]$/.test(key)) {
            if (calc.error) return;
            if (calc.fresh) {
                calc.display = key;
                calc.fresh = false;
            } else {
                calc.display =
                    (calc.display === "0" ? "" : calc.display) + key;
            }
            if (calc.display.length > 16) calc.display = calc.display.slice(0, 16);
        } else if (key === ".") {
            if (calc.error) return;
            if (calc.fresh) {
                calc.display = "0.";
                calc.fresh = false;
            } else if (!calc.display.includes(".")) {
                calc.display += ".";
            }
        } else if (["+", "-", "*", "/"].includes(key)) {
            if (calc.acc !== null && calc.op && !calc.fresh) {
                const res = evalOp(calc.acc, num(), calc.op);
                if (res === null) {
                    calc.error = true;
                    calc.display = "Ошибка";
                    return;
                }
                calc.acc = res;
                calc.display = fmt(res);
            } else {
                calc.acc = num();
            }
            calc.op = key;
            calc.fresh = true;
        } else if (key === "=") {
            if (calc.error) return;
            if (calc.acc !== null && calc.op) {
                const res = evalOp(calc.acc, num(), calc.op);
                if (res === null) {
                    calc.error = true;
                    calc.display = "Ошибка";
                    return;
                }
                calc.display = fmt(res);
                calc.acc = null;
                calc.op = null;
            }
            calc.fresh = true;
        } else if (key === "C") {
            Object.assign(calc, {
                display: "0",
                acc: null,
                op: null,
                fresh: true,
                error: false,
            });
        } else if (key === "CE") {
            calc.display = "0";
            calc.fresh = true;
            calc.error = false;
        } else if (key === "Back") {
            if (calc.fresh || calc.error) return;
            calc.display =
                calc.display.length > 1 ? calc.display.slice(0, -1) : "0";
            if (calc.display === "-") calc.display = "0";
        } else if (key === "sqrt") {
            const v = num();
            if (v < 0) {
                calc.error = true;
                calc.display = "Ошибка";
                return;
            }
            calc.display = fmt(Math.sqrt(v));
            calc.fresh = true;
        } else if (key === "%") {
            if (calc.acc !== null && calc.op) {
                calc.display = fmt((calc.acc * num()) / 100);
            }
            calc.fresh = true;
        } else if (key === "1/x") {
            const v = num();
            if (v === 0) {
                calc.error = true;
                calc.display = "Ошибка";
                return;
            }
            calc.display = fmt(1 / v);
            calc.fresh = true;
        } else if (key === "±") {
            if (calc.error) return;
            if (calc.display !== "0") {
                calc.display = calc.display.startsWith("-")
                    ? calc.display.slice(1)
                    : "-" + calc.display;
            }
        } else if (key === "MC") {
            calc.mem = 0;
        } else if (key === "MR") {
            calc.display = fmt(calc.mem);
            calc.fresh = true;
        } else if (key === "MS") {
            calc.mem = num();
        } else if (key === "M+") {
            calc.mem += num();
        }
    }

    function evalOp(a, b, op) {
        switch (op) {
            case "+":
                return a + b;
            case "-":
                return a - b;
            case "*":
                return a * b;
            case "/":
                return b === 0 ? null : a / b;
        }
        return null;
    }

